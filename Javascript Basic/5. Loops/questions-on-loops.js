// Q. no 1 --> Print number 10-1 using while loop
let i2 = 10;
while (i2 >= 1) {
    console.log(i2);
    i2--;
}

// Q. no 2 --> Print all even number from 1-20 using for loop

for (let i = 2; i <= 20; i += 2) {
    console.log(i)
}

// Q. no 3 --> Print all odd number 1 to 15 using while loop

let odd = 1;
while (odd <= 15) {
    console.log(odd);
    odd += 2;
}

// Q 5 --> Multiplication table of 5

for (let i = 1; i <= 10; i++) {
    console.log(`5 X ${i} = ${i * 5}`)
}